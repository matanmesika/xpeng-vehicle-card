"""Render the *real* v0.7 Studio Cockpit in Chromium (desktop + phone).

Screenshots are generated by the installed card source with missing live XPENG
telemetry, not composited concept images or mock API data.
"""
from pathlib import Path
import shutil
from playwright.sync_api import sync_playwright

ROOT=Path(__file__).resolve().parents[1]
SCRIPT=(ROOT/'dist/xpeng-vehicle-card.js').read_text(encoding='utf-8')
assert SCRIPT==(ROOT/'src/xpeng-vehicle-card.js').read_text(encoding='utf-8')
assert 'XPENG Vehicle Card v0.7.0-alpha.1' in SCRIPT
assert 'localStorage' not in SCRIPT
OUT=ROOT/'previews'/'cockpit-v070'
OUT.mkdir(parents=True,exist_ok=True)
DATA={'sensor.my_xpeng_api_connection_status':{'state':'not_configured','attributes':{}}}
with sync_playwright() as playwright:
 browser=playwright.chromium.launch(headless=True,executable_path=shutil.which('chromium') or None,args=['--no-sandbox'])
 for device,width,height in [('desktop',1512,1100),('phone',390,844)]:
  page=browser.new_page(viewport={'width':width,'height':height},device_scale_factor=1)
  errors=[]
  page.on('pageerror',lambda error:errors.append(str(error)))
  asset_failures=[]
  def asset(route):
   path=ROOT/'assets'/route.request.url.split('/local/xpeng/',1)[-1]
   if not path.is_file():
    asset_failures.append(str(path))
    return route.fulfill(status=404,body='File not found')
   media='image/webp' if path.suffix=='.webp' else 'image/png' if path.suffix=='.png' else 'image/svg+xml'
   route.fulfill(status=200,body=path.read_bytes(),content_type=media)
  page.route('**/local/xpeng/**',asset)
  page.set_content('<html><head><base href="https://ha.local/"><meta charset="utf-8"><style>html,body{padding:0;margin:0;background:#09111b}xpeng-vehicle-card{display:block;width:100%}</style></head><body><xpeng-vehicle-card></xpeng-vehicle-card></body></html>')
  page.add_script_tag(content=SCRIPT)
  page.evaluate("""states=>{
   const el=document.querySelector('xpeng-vehicle-card');
   el.setConfig({
     prefix:'my_xpeng',model:'G6',year:'2026',trim:'core_performance_awd',
     color:'arctic_white',interior:'dark_gray',theme:'dark',
     dashboard_layout:'cockpit',image_path:'/local/xpeng'
   });
   el.hass={states};
  }""",DATA)
  card=page.locator('xpeng-vehicle-card')
  assert card.get_attribute('data-cockpit') is not None
  assert card.locator('.xs-hero').count()==1
  assert card.locator('.xs-car-photo').count()==1
  page.wait_for_function("""()=>{const i=document.querySelector('xpeng-vehicle-card').shadowRoot.querySelector('.xs-car-photo');return i&&i.complete&&i.naturalWidth>800}""",timeout=15000)
  assert card.locator('.xs-brand img').count()==0  # no broken logo dependency
  assert card.locator('.xs-sidebar .xs-nav [data-view]').count()==9
  assert card.locator('.xs-action').count()==5
  assert card.locator('.xs-module').count()==4
  assert card.locator('.xs-not-connected').count()==1
  assert card.locator('.xs-head-reading').inner_text().count('—')>=2
  assert card.locator('[data-view="appearance"],[data-color],[data-interior]').count()==0
  assert card.locator('button[data-command],button[data-call-service]').count()==0
  assert card.locator('.xs-hero-detail').count()==0
  page.screenshot(path=str(OUT/f'{device}-overview.png'),full_page=True)
  card.locator('.xs-nav button[data-view="controls"]').click()
  assert card.locator('.xs-hero[data-cockpit-view="controls"]').count()==1
  assert card.locator('.xs-car-photo').count()==1
  assert card.locator('.xs-hero-map').count()==1
  assert 'Not available' in card.locator('.xs-data-grid').inner_text()
  page.screenshot(path=str(OUT/f'{device}-controls.png'),full_page=True)
  card.locator('.xs-nav button[data-view="climate"]').click()
  assert card.locator('.xs-hero[data-cockpit-view="climate"]').count()==1
  assert card.locator('.xs-hero-cabin svg.xp-cabin-svg').count()==1
  page.screenshot(path=str(OUT/f'{device}-climate.png'),full_page=True)
  card.locator('.xs-nav button[data-view="comfort"]').click()
  assert card.locator('.xs-hero[data-cockpit-view="comfort"]').count()==1
  assert card.locator('.xs-comfort-item').count()==8
  assert 'Steering wheel heating' in card.locator('.xs-comfort-grid').inner_text()
  assert card.locator('.xs-comfort-item button:not([disabled])').count()==0
  page.screenshot(path=str(OUT/f'{device}-comfort.png'),full_page=True)
  card.locator('.xs-nav button[data-view="charging"]').click()
  assert card.locator('.xs-hero[data-cockpit-view="charging"]').count()==1
  assert '—' in card.locator('.xs-charge-meter').inner_text()
  page.screenshot(path=str(OUT/f'{device}-charging.png'),full_page=True)
  card.locator('.xs-nav button[data-view="tires"]').click()
  assert card.locator('.xs-hero[data-cockpit-view="tires"]').count()==1
  assert card.locator('.xs-hero-map').count()==1
  page.screenshot(path=str(OUT/f'{device}-tires.png'),full_page=True)
  card.locator('.xs-nav button[data-view="interior"]').click()
  assert 'Dark Gray' in card.locator('.xs-detail').inner_text()
  assert card.locator('.xs-hero-cabin').count()==1
  page.screenshot(path=str(OUT/f'{device}-interior.png'),full_page=True)
  card.locator('button[data-expand]').click()
  assert card.get_attribute('data-expanded') is not None
  card.locator('button[data-expand]').click()
  assert card.get_attribute('data-expanded') is None
  # The card should not grow wider than its viewport on phones.
  if device=='phone':
   page.evaluate("()=>{document.querySelector('xpeng-vehicle-card')._view='overview';document.querySelector('xpeng-vehicle-card').render();}")
   sizes=page.evaluate("""()=>{const s=document.querySelector('xpeng-vehicle-card').shadowRoot;
    return {viewport:innerWidth,body:document.body.scrollWidth,cockpit:s.querySelector('.xp-studio').getBoundingClientRect().width}}""")
   assert sizes['body']<=sizes['viewport']+3,sizes
   assert sizes['cockpit']<=sizes['viewport']+3,sizes
   # Every navigation tab should be discoverable without hidden single-tab scrolling.
   nav=page.evaluate("""()=>{const c=document.querySelector('xpeng-vehicle-card').shadowRoot;return [...c.querySelectorAll('.xs-nav button')].map(b=>({r:b.getBoundingClientRect().right,w:innerWidth}))}""")
   assert all(row['r']<=row['w']+2 for row in nav),nav
  assert not errors,errors
  assert not asset_failures,asset_failures
  page.close()
 browser.close()
print('PASS: real-artwork Studio cockpit screenshots, 7 views x desktop/phone, safe unavailable values, full screen')
